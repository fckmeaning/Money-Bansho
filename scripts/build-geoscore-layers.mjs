// Vercel Edge refuses a plain-JavaScript function that imports TypeScript, so the
// static map layers used by the dossier API are compiled into one module.
// Run after editing shared/geo-data.ts, military-bases-data.ts or
// nuclear-facilities-data.ts: node scripts/build-geoscore-layers.mjs
import { build } from 'esbuild';

await build({
  stdin: {
    contents: [
      "export { CONFLICT_ZONES, INTEL_HOTSPOTS, STRATEGIC_WATERWAYS } from './shared/geo-data.ts';",
      "export { MILITARY_BASES_EXPANDED } from './shared/military-bases-data.ts';",
      "export { NUCLEAR_FACILITIES } from './shared/nuclear-facilities-data.ts';",
    ].join('\n'),
    resolveDir: '.',
    loader: 'ts',
  },
  bundle: true,
  format: 'esm',
  charset: 'utf8',
  banner: { js: '// Generated by scripts/build-geoscore-layers.mjs. Do not edit.' },
  outfile: 'api/_dossier/geoscore-layers.generated.js',
});
