import type { StoryData } from './story-data';
import { getCanonicalApiOrigin } from '@/services/runtime';

const VALID_STORY_TYPES = ['ciianalysis', 'convergence', 'brief'] as const;
type StoryType = typeof VALID_STORY_TYPES[number];

function sanitizeCountryCode(value: string): string {
  const code = String(value || '').trim().toUpperCase();
  return /^[A-Z]{2}$/.test(code) ? code : '';
}

function sanitizeStoryType(value: string | null): StoryType {
  const t = String(value || '').trim().toLowerCase();
  return (VALID_STORY_TYPES as readonly string[]).includes(t) ? (t as StoryType) : 'ciianalysis';
}

// Deep link generator for story sharing
export function generateStoryDeepLink(
  countryCode: string,
  type: 'ciianalysis' | 'convergence' | 'brief' = 'ciianalysis',
  score?: number,
  level?: string
): string {
  const safeCountryCode = sanitizeCountryCode(countryCode);
  const safeType = sanitizeStoryType(type);
  const params = new URLSearchParams({
    c: safeCountryCode,
    t: safeType,
    ts: Date.now().toString()
  });
  if (score !== undefined) params.set('s', String(score));
  if (level) params.set('l', String(level).trim().slice(0, 32));
  return `${getCanonicalApiOrigin()}/story?${params.toString()}`;
}

// Parse deep link parameters
export function parseStoryParams(url: URL): { countryCode: string; type: string } | null {
  const countryCode = url.searchParams.get('c');
  if (!countryCode) return null;
  const safeCountryCode = sanitizeCountryCode(countryCode);
  if (!safeCountryCode) return null;
  return {
    countryCode: safeCountryCode,
    type: sanitizeStoryType(url.searchParams.get('t'))
  };
}

// One line about the index; a country without it says so.
const indexLine = (data: StoryData): string => (data.cii
  ? `Money Bansho instability index: ${data.cii.score}/100`
  : 'Instability: Unavailable');
const threatLines = (data: StoryData): string => (
  `${data.threats.critical > 0 ? `Critical threats: ${data.threats.critical}\n` : ''}`
  + `${data.threats.high > 0 ? `High threats: ${data.threats.high}\n` : ''}`
);

// Share text templates for different platforms
export const shareTexts = {
  twitter: (data: StoryData) =>
    `${data.countryName} Intelligence Brief\n\n${indexLine(data)}\n${threatLines(data)}\nGenerated by Money Bansho`,

  whatsapp: (data: StoryData) =>
    `*${data.countryName} Intelligence Brief*\n\n${indexLine(data)}\n${threatLines(data)}`
    + `\nView full analysis: ${generateStoryDeepLink(data.countryCode, 'ciianalysis', data.cii?.score, data.cii?.level)}`,

  linkedin: (data: StoryData) =>
    `Intelligence Update: ${data.countryName}\n\n${indexLine(data)}\n${threatLines(data)}`
    + '\nData via Money Bansho - open-source market and event monitoring',

  telegram: (data: StoryData) =>
    `*${data.countryName} Intelligence*\n\n${indexLine(data)}\n${threatLines(data)}`
    + `\n${generateStoryDeepLink(data.countryCode, 'ciianalysis', data.cii?.score, data.cii?.level)}`
};

// Pre-generated share URLs
export function getShareUrls(data: StoryData): Record<string, string> {
  const url = generateStoryDeepLink(data.countryCode, 'ciianalysis', data.cii?.score, data.cii?.level);
  const text = encodeURIComponent(shareTexts.twitter(data));
  
  return {
    twitter: `https://twitter.com/intent/tweet?text=${text}&url=${encodeURIComponent(url)}`,
    linkedin: `https://www.linkedin.com/sharing/share-offsite/?url=${encodeURIComponent(url)}`,
    reddit: `https://reddit.com/submit?url=${encodeURIComponent(url)}&title=${encodeURIComponent(`${data.countryName} Intelligence Brief - Money Bansho`)}`,
    facebook: `https://www.facebook.com/sharer/sharer.php?u=${encodeURIComponent(url)}`,
    whatsapp: `https://wa.me/?text=${encodeURIComponent(shareTexts.whatsapp(data))}`,
    telegram: `https://t.me/share/url?url=${encodeURIComponent(url)}&text=${encodeURIComponent(shareTexts.telegram(data))}`,
  };
}
