export function nameOf(id: string, lang: Lang): string {
  const key = id.toLowerCase();
  const found = Object.prototype.hasOwnProperty.call(NAMES, key) ? NAMES[key] : undefined;
  return found ? found[lang === 'ru' ? 1 : 0] : id;
}
