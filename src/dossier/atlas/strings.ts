export type Strings = (key: Key, values?: Record<string, string | number>) => string;

export function texts(lang: Lang): Strings {
  const table = lang === 'ru' ? RU : EN;
  return (key, values = {}) =>
    table[key].replace(/\{(\w+)\}/g, (all, name: string) => (name in values ? String(values[name]) : all));
}
