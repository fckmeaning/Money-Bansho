// Builds api/_dossier/feeds.js: a compact, server-usable list of RSS/Atom feeds
// taken from the repo's own catalog (shared/news-catalog.json + shared/source-tiers.json).
// Run: node scripts/build-dossier-feeds.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const catalog = JSON.parse(readFileSync('shared/news-catalog.json', 'utf8'));
const tiers = JSON.parse(readFileSync('shared/source-tiers.json', 'utf8'));

// Catalog category -> dossier group. Priority = order of the keys below.
const GROUPS = [
  ['corp', ['corporate-leadership', 'layoffs']],
  ['fin', ['finance', 'markets', 'centralbanks', 'fin-regulation', 'economic', 'forex', 'bonds', 'institutional', 'analysis',
    'derivatives', 'commodities', 'energy', 'commodity-news', 'gold-silver', 'mining-news', 'critical-minerals', 'base-metals',
    'mining-companies', 'supply-chain', 'commodity-regulation', 'ipo', 'fintech', 'nq-news', 'funding']],
  ['china', ['china-media']],
  ['israel', ['israel']],
  ['korea', ['north-korea']],
  ['europe', ['europe-business', 'europe']],
  ['us', ['us']],
  ['asia', ['asia']],
  ['mideast', ['middleeast', 'gccNews']],
  ['world', ['politics', 'intel', 'thinktanks', 'gov', 'policy', 'crisis', 'live-news']],
  ['tech', ['tech', 'ai', 'hardware', 'cloud', 'security', 'outages']],
  ['latam', ['latam']],
  ['africa', ['africa']],
];
const groupOf = new Map();
GROUPS.forEach(([group, cats], rank) => cats.forEach((c) => groupOf.set(c, { group, rank })));

const seen = new Map();
for (const feed of catalog.feeds) {
  if (typeof feed.url !== 'string' || !/^https?:\/\//.test(feed.url)) continue;
  let best = null;
  for (const p of feed.placements || []) {
    const g = groupOf.get(p.category);
    if (g && (!best || g.rank < best.rank)) best = g;
  }
  if (!best) continue;
  if (seen.has(feed.url)) continue;
  const tier = tiers[feed.name];
  const host = new URL(feed.url).hostname.replace(/^www\./, '');
  seen.set(feed.url, {
    n: feed.name,
    u: feed.url,
    g: best.group,
    t: Number.isInteger(tier) && tier >= 1 && tier <= 4 ? tier : 3,
    ...(feed.lang ? { l: feed.lang } : {}),
    ...(host === 'news.google.com' ? { gn: 1 } : {}),
  });
}
const list = [...seen.values()];
const counts = {};
for (const f of list) counts[f.g] = (counts[f.g] || 0) + 1;
const body = `// GENERATED by scripts/build-dossier-feeds.mjs from shared/news-catalog.json. Do not edit by hand.
// n name, u url, g group, t source tier (1 best .. 4), l language, gn = Google News site search.
export const FEEDS = ${JSON.stringify(list)};
`;
writeFileSync('api/_dossier/feeds.js', body.replace(/\},\{/g, '},\n{'));
console.log('feeds', list.length, counts, 'google-news', list.filter((f) => f.gn).length);
